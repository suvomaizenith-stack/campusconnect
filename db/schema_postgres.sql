-- Idempotent. Every table has RLS enabled and no policies: only the server role (DATABASE_URL) can read or write.

-- One-time cleanup: the first schema version had email/password staff and a thin tickets table, holding demo rows only.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = 'staff' AND column_name = 'email') THEN
        DROP TABLE IF EXISTS confirmations, drafts, comments, status_history, tickets, staff CASCADE;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    roll_no TEXT NOT NULL UNIQUE,
    pin_hash TEXT NOT NULL,
    failed_attempts INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    department TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'staff',
    access_key_hash TEXT NOT NULL,
    failed_attempts INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS landmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT UNIQUE,
    category TEXT NOT NULL DEFAULT 'place',
    number INT,
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    outside_campus BOOLEAN NOT NULL DEFAULT FALSE,
    floors TEXT[] NOT NULL DEFAULT '{}'
);

-- One group per real-world problem (e.g. "leaking tap, Block A 2nd floor"). Many tickets can link to it.
CREATE TABLE IF NOT EXISTS issue_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    landmark_id BIGINT REFERENCES landmarks(id),
    floor TEXT,
    title TEXT NOT NULL,
    keywords TEXT[] NOT NULL DEFAULT '{}',
    status TEXT NOT NULL DEFAULT 'open',
    level TEXT NOT NULL DEFAULT 'normal',
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    eta_at TIMESTAMPTZ,
    latest_note TEXT,
    first_reported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_reported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(id),
    student_name TEXT,
    student_roll TEXT,
    title TEXT NOT NULL,
    description TEXT,
    category TEXT NOT NULL,
    severity INT NOT NULL DEFAULT 1,
    priority_score INT NOT NULL DEFAULT 0,
    tier TEXT NOT NULL DEFAULT 'normal',
    status TEXT NOT NULL DEFAULT 'waiting',
    landmark_id BIGINT REFERENCES landmarks(id),
    floor TEXT,
    room TEXT,
    nearby TEXT,
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    group_id BIGINT REFERENCES issue_groups(id),
    dup_review TEXT NOT NULL DEFAULT 'none',
    info_complete BOOLEAN NOT NULL DEFAULT TRUE,
    needs_review BOOLEAN NOT NULL DEFAULT FALSE,
    missing_fields TEXT[] NOT NULL DEFAULT '{}',
    follow_up_question TEXT,
    assigned_to BIGINT REFERENCES staff(id),
    eta_at TIMESTAMPTZ,
    self_resolved BOOLEAN NOT NULL DEFAULT FALSE,
    photo BYTEA,
    photo_mime TEXT,
    photo_note TEXT,
    ai_mode TEXT,
    ai_confidence DOUBLE PRECISION,
    language TEXT,
    urgency_override TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS tickets_student_idx ON tickets (student_id);
CREATE INDEX IF NOT EXISTS tickets_group_idx ON tickets (group_id);
CREATE INDEX IF NOT EXISTS tickets_assigned_idx ON tickets (assigned_to, status);

CREATE TABLE IF NOT EXISTS status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    status TEXT NOT NULL,
    note TEXT,
    changed_by TEXT,
    internal BOOLEAN NOT NULL DEFAULT FALSE,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ticket_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id BIGINT NOT NULL REFERENCES tickets(id),
    sender_role TEXT NOT NULL,
    sender_name TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per student per group: their own ticket or an "I face this too" tap.
CREATE TABLE IF NOT EXISTS group_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES issue_groups(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    ticket_id BIGINT REFERENCES tickets(id),
    source TEXT NOT NULL DEFAULT 'ticket',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (group_id, student_id)
);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES issue_groups(id),
    level TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    acknowledged_by TEXT,
    acknowledged_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_by TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    location TEXT,
    kind TEXT,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS drafts_student_idx ON drafts (student_id);

